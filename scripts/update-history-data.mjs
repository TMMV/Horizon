// Builds data/history.js: yearly market history for replaying past periods.
//
//   Shares and bonds: US S&P 500 (with dividends) and 10-year Treasury bond total returns,
//                     1928 onwards (Aswath Damodaran, NYU Stern), turned into real returns
//                     with US CPI-U December-to-December inflation (BLS via FRED, CPIAUCNS).
//   UK inflation:     ONS long-run Retail Prices Index (CDKO, annual average), year on year.
//
// The app replays the real returns on top of UK inflation, so a sequence keeps its real
// (after-inflation) character while prices, rents and tax thresholds follow UK history.
// Run: node scripts/update-history-data.mjs

import { writeFile } from 'node:fs/promises';

const SOURCES = {
  returns: 'https://pages.stern.nyu.edu/~adamodar/New_Home_Page/datafile/histretSP.html',
  usCpi: 'https://fred.stlouisfed.org/graph/fredgraph.csv?id=CPIAUCNS',
  ukPrices: 'https://www.ons.gov.uk/economy/inflationandpriceindices/timeseries/cdko/mm23/data',
};

async function get(url) {
  const res = await fetch(url, { headers: { 'User-Agent': 'horizon-planner (history data refresh)' } });
  if (!res.ok) throw new Error(`${url}: HTTP ${res.status}`);
  return res.text();
}

const decode = s => s.replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/&amp;/g, '&').replace(/\s+/g, ' ').trim();
const pct = s => parseFloat(s.replace('%', '')) / 100;

async function main() {
  // Annual returns table: Year | S&P 500 | small cap | T.Bill | T.Bond | ...
  const html = await get(SOURCES.returns);
  const rows = [...html.matchAll(/<tr[^>]*>([\s\S]*?)<\/tr>/gi)].map(m => [...m[1].matchAll(/<t[dh][^>]*>([\s\S]*?)<\/t[dh]>/gi)].map(c => decode(c[1])));
  const header = rows.find(r => r[0] === 'Year');
  const iStock = header.findIndex(h => /^S&P 500/.test(h));
  const iBond = header.findIndex(h => /T\. ?Bond/.test(h));
  const returns = new Map();
  for (const r of rows) {
    if (!/^(19|20)\d\d$/.test(r[0])) continue;
    returns.set(+r[0], { stocks: pct(r[iStock]), bonds: pct(r[iBond]) });
  }

  // US CPI, December to December.
  const dec = new Map();
  for (const line of (await get(SOURCES.usCpi)).trim().split('\n').slice(1)) {
    const [date, v] = line.split(',');
    if (date.slice(5, 7) === '12') dec.set(+date.slice(0, 4), +v);
  }

  // UK RPI long-run annual index.
  const uk = new Map(JSON.parse(await get(SOURCES.ukPrices)).years.map(y => [+y.year, +y.value]));

  const years = [...returns.keys()].filter(y => dec.has(y) && dec.has(y - 1) && uk.has(y) && uk.has(y - 1)).sort((a, b) => a - b);
  const r4 = v => Math.round(v * 10000) / 10000;
  const data = {
    asOf: new Date().toISOString().slice(0, 10),
    note: 'Real (after US inflation) total returns on US shares (S&P 500) and 10-year Treasury bonds, and UK inflation (RPI), by calendar year.',
    sources: {
      returns: 'Aswath Damodaran, Historical Returns on Stocks, Bonds and Bills (NYU Stern)',
      usInflation: 'US CPI-U (BLS), via FRED series CPIAUCNS',
      ukInflation: 'ONS Retail Prices Index long-run series (CDKO)',
    },
    years,
    stocksReal: years.map(y => r4((1 + returns.get(y).stocks) / (dec.get(y) / dec.get(y - 1)) - 1)),
    bondsReal: years.map(y => r4((1 + returns.get(y).bonds) / (dec.get(y) / dec.get(y - 1)) - 1)),
    ukInflation: years.map(y => r4(uk.get(y) / uk.get(y - 1) - 1)),
  };
  const body = `// Generated by scripts/update-history-data.mjs. Do not edit by hand.
// ${data.note}
(function (root) {
  const HISTORY = ${JSON.stringify(data, null, 2)};
  if (typeof module !== 'undefined' && module.exports) module.exports = HISTORY;
  else root.HISTORY_DATA = HISTORY;
})(typeof globalThis !== 'undefined' ? globalThis : this);
`;
  await writeFile(new URL('../data/history.js', import.meta.url), body);
  console.log(`data/history.js: ${years[0]}–${years[years.length - 1]} (${years.length} years)`);
}

main().catch(e => { console.error(e.message); process.exit(1); });
